import { expect, test } from '@playwright/test'

test('isolated public visitors change inputs and confirm simulated purchase', async ({ browser }) => {
  const baseURL = process.env.PUBLIC_DEMO_URL ?? 'http://127.0.0.1'
  const first = await browser.newContext({ baseURL })
  const second = await browser.newContext({ baseURL })
  try {
    const a = await first.newPage()
    const b = await second.newPage()
    await a.goto('/')
    await expect(a.getByRole('heading', { name: 'Enterprise AI Operations Hub' })).toBeVisible()
    await a.getByRole('link', { name: '開啟採購 Demo' }).click()
    await expect(a).toHaveURL(/\/operations\/$/)
    const unconfigured = await b.goto('/manufacturing/')
    expect(unconfigured?.status()).toBe(404)
    await b.goto('/operations/')
    await a.getByRole('button', { name: '開始模擬' }).click()
    await b.getByRole('button', { name: '開始模擬' }).click()
    await expect(a.getByRole('heading', { name: '採購 Workflow Console' })).toBeVisible()
    expect(await first.cookies()).toContainEqual(expect.objectContaining({ name: 'hub_demo', path: '/operations/' }))
    await a.getByLabel('採購需求').fill('請評估採購 P-300')
    await a.getByRole('button', { name: '建立採購草稿' }).click()
    await expect(a.getByText(/採購缺口：16/)).toBeVisible()
    await expect(b.getByText('目前沒有任務')).toBeVisible()
    await a.getByRole('button', { name: '切換為 manager' }).click()
    await a.getByLabel('編輯 SKU').fill('P-300')
    await a.getByLabel('庫存數量').fill('10')
    await a.getByRole('button', { name: '新增或儲存產品' }).click()
    await expect(a.getByText(/資料或規則已更新：請重新建立草稿/)).toBeVisible()
    await expect(b.getByText(/P-300 · Actuator Demo · 庫存 4/)).toBeVisible()
    await a.getByLabel('採購公式').selectOption('safety_stock')
    await a.getByLabel('安全庫存').fill('5')
    await a.getByRole('button', { name: '預覽 P-300' }).click()
    await expect(a.getByText(/預覽 P-300.*= 15/)).toBeVisible()
    await a.getByRole('button', { name: '發布規則' }).click()
    await a.getByLabel('採購需求').fill('請評估採購 P-300')
    await a.getByRole('button', { name: '建立採購草稿' }).click()
    await expect(a.getByText(/採購缺口：15/)).toBeVisible()
    const confirm = a.getByRole('button', { name: '人工確認並提交' }).first()
    await expect(confirm).toBeEnabled()
    await confirm.click()
    await expect(a.getByText(/採購單 #/)).toBeVisible()
    await a.getByRole('button', { name: '查詢 EIP 簽核' }).click()
    await expect(a.getByText(/採購單 #\d+ · EIP 簽核 #\d+ · pending/)).toBeVisible()
    await expect(b.getByText('目前沒有任務')).toBeVisible()
  } finally { await first.close(); await second.close() }
})
